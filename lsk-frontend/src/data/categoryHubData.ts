export interface HubItem {
  id: string;              // 고유 식별자 (예: 'headache-dizziness')
  name: string;            // 서브메뉴 국문명 (예: '두통·어지럼증')
  englishTitle: string;    // 영문명 (예: 'Headache & Dizziness Clinic')
  href: string;            // 상세 페이지 이동 경로 (예: '/neurosurgery/headache-dizziness')
  badge: string;           // 진료 특성 뱃지 (예: '정밀진단', '비수술', '특화클리닉')
  tagline: string;         // 핵심 한 줄 슬로건
  description: string;     // 질환 및 진료에 대한 친절한 요약 설명
  symptoms: string[];      // 주요 의심 증상 3~4가지 체크리스트
  treatments: string[];    // 대표 검사 및 치료 방법 태그
  iconType: "brain" | "spine" | "joint" | "surgery" | "medical" | "checkup" | "women" | "about"; // 테마 아이콘
}

export interface CategoryHubInfo {
  id: string;              // 대메뉴 슬러그 (예: 'neurosurgery', 'spine', 'knee-hip')
  title: string;           // 대메뉴 한글명 (예: '뇌신경센터')
  englishTitle: string;    // 영문 타이틀 (예: 'NEUROLOGY & NEUROSURGERY CENTER')
  slogan: string;          // 센터 대표 슬로건
  description: string;     // 센터 소개 상세 문구
  badge: string;           // 대표 인증/특장점 뱃지
  stats: { label: string; value: string }[]; // 센터 신뢰 지표 (예: 임상경험, 첨단장비 등)
  items: HubItem[];        // 지그재그로 노출될 서브메뉴 상세 카드 목록
}

